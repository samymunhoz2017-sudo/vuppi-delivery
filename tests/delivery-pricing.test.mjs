import assert from 'node:assert/strict';
import {quoteDelivery} from '../server/delivery-pricing.mjs';
const tariff={cityId:'pitangueiras-sp',enabled:true,version:1,baseDistanceM:2000,baseCents:800,additionalStepM:1000,additionalStepCents:150,minimumCents:800,maximumDistanceM:30000,returnCents:300};
assert.equal(quoteDelivery({cityId:'pitangueiras-sp',distanceM:2000},tariff).totalCents,800);
assert.equal(quoteDelivery({cityId:'pitangueiras-sp',distanceM:2001},tariff).totalCents,950);
assert.equal(quoteDelivery({cityId:'pitangueiras-sp',distanceM:3500},tariff).totalCents,1100);
assert.equal(quoteDelivery({cityId:'pitangueiras-sp',distanceM:3500,returnRequired:true},tariff).totalCents,1400);
assert.throws(()=>quoteDelivery({cityId:'pitangueiras-sp',distanceM:30001},tariff),/limite/);
assert.throws(()=>quoteDelivery({cityId:'outra',distanceM:1000},tariff),/cidade/);
assert.throws(()=>quoteDelivery({cityId:'pitangueiras-sp',distanceM:1000}, {...tariff,establishmentId:'loja'}),/estabelecimento/);
const quote=quoteDelivery({cityId:'pitangueiras-sp',distanceM:3500},tariff);tariff.baseCents=9999;assert.equal(quote.snapshot.totalCents,1100);
console.log('Precificação: base, degraus, mínimo, retorno, limite e snapshot aprovados.');
